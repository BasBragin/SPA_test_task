"""Конфигурация для Части 2: прогноз потребности и рекомендация закупки.

Все параметры вынесены сюда, чтобы избежать «магических чисел» в коде.
"""

from __future__ import annotations

# ─── Прогноз ──────────────────────────────────────────────────────────
# Коэффициент экспоненциального сглаживания (EWMA).
# α = 0.3 — умеренный вес последних наблюдений.
# Обоснование: 12 недель истории, тренд заметен, но не доминирует.
EWMA_ALPHA: float = 0.3

# Количество недель в месяце (для пересчёта).
DAYS_PER_WEEK: int = 7

# ─── Детекция скачков (changepoint) ──────────────────────────────────
# Минимальный размер сегмента слева и справа от точки разрыва.
# 2 — нужно хотя бы 2 точки с каждой стороны, чтобы доверять средним.
CHANGEPOINT_MIN_SEGMENT: int = 2

# Порог относительного роста: right_mean / left_mean > 1.5 = скачок.
# 1.5 — рост на 50% уже значим, ниже — плавный тренд.
CHANGEPOINT_RATIO_THRESHOLD: float = 1.5

# Максимальный коэффициент вариации справа от скачка.
# Если CV > 0.25 — данные «пилообразные», не считаем скачок устойчивым.
CHANGEPOINT_CV_MAX: float = 0.25

# ─── Confidence ──────────────────────────────────────────────────────
# Базовая уверенность при идеальных данных.
CONFIDENCE_BASE: float = 1.0

# Минимальная длина истории (в неделях) для полной уверенности.
# Меньше — уверенность снижается пропорционально.
CONFIDENCE_MIN_WEEKS: int = 12

# Минимальный множитель уверенности при высокой волатильности.
CONFIDENCE_MIN_VOLATILITY_FACTOR: float = 0.3

# Порог «требуется уточнение»: confidence < 0.6 → флаг.
CONFIDENCE_UNKNOWN_THRESHOLD: float = 0.6

# ─── Рекомендация закупки ────────────────────────────────────────────
# Минимальный горизонт прогноза (дней).
MIN_HORIZON_DAYS: int = 1

# Максимальный горизонт прогноза (дней).
MAX_HORIZON_DAYS: int = 365